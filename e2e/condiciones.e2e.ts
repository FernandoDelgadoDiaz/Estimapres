import {test,expect} from '@playwright/test'
test('condiciones opcionales, conflictos duros y preferencias sin persistencia',async({page})=>{
 const writes:string[]=[]
 page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))writes.push(r.url())})
 await page.goto('/lab-condiciones.html')
 await page.getByRole('button',{name:'Verificar y generar prueba'}).click()
 await expect(page.getByRole('heading',{name:'Propuesta de laboratorio'})).toBeVisible()
 await page.getByRole('button',{name:'Agregar condición'}).click()
 await page.getByLabel('Día',{exact:true}).selectOption('1')
 await page.getByRole('button',{name:'Agregar condición'}).click()
 await page.getByRole('button',{name:'Verificar y generar prueba'}).click()
 await expect(page.getByRole('alert')).toContainText('CONTRATO_INDIVIDUAL_INVIABLE')
 await expect(page.getByRole('heading',{name:'Propuesta de laboratorio'})).toHaveCount(0)
 await page.getByRole('button',{name:'Quitar condición 2'}).click()
 await page.getByRole('button',{name:'Quitar condición 1'}).click()
 await page.getByLabel('Prioridad').selectOption('PREFERIRIA')
 await page.getByRole('button',{name:'Agregar condición'}).click()
 await page.getByLabel('Día',{exact:true}).selectOption('0')
 await page.getByRole('button',{name:'Agregar condición'}).click()
 await page.getByRole('button',{name:'Verificar y generar prueba'}).click()
 await expect(page.getByRole('heading',{name:'Propuesta de laboratorio'})).toBeVisible()
 expect(writes).toEqual([])
 expect(await page.evaluate(()=>({local:Object.keys(localStorage),session:Object.keys(sessionStorage)}))).toEqual({local:[],session:[]})
})
